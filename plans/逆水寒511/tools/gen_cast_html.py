def render_design_review(overview):
    """仅渲染总纲集中审阅区用到的格式；新块格式报错，避免静默漏掉设计。"""
    start = '### 本次体验反馈核查（2026-11-16）'
    end = '### 给接手agent的开工说明（先读这一段）'
    if overview.count(start) != 1 or overview.count(end) != 1:
        raise ValueError('project overview review boundaries missing or duplicated')
    source = overview.split(start, 1)[1].split(end, 1)[0]
    lines = (start + source).strip().splitlines()

    def inline(value):
        tokens = r'`[^`]+`|\*\*.+?\*\*|\[[^\]]+\]\([^\s)]+\)'
        out, cursor = [], 0
        for match in re.finditer(tokens, value):
            out.append(html.escape(value[cursor:match.start()]))
            token = match.group()
            if token.startswith('`'):
                out.append('<code>' + html.escape(token[1:-1]) + '</code>')
            elif token.startswith('**'):
                out.append('<strong>' + inline(token[2:-2]) + '</strong>')
            else:
                label, target = re.fullmatch(r'\[([^\]]+)\]\(([^\s)]+)\)', token).groups()
                if target.startswith('#'):
                    target = os.path.basename(OVERVIEW) + target
                if ':' in target or target.startswith('//'):
                    raise ValueError('unsupported design review link: ' + target)
                out.append('<a href="' + html.escape(target, quote=True) + '">'
                           + inline(label) + '</a>')
            cursor = match.end()
        out.append(html.escape(value[cursor:]))
        return ''.join(out)

    def cells(line):
        return [cell.strip() for cell in line.strip().strip('|').split('|')]

    out, i = [], 0
    while i < len(lines):
        line = lines[i].strip()
        if not line:
            i += 1
            continue
        if line.startswith('### '):
            out.append('<h3>' + inline(line[4:]) + '</h3>')
            i += 1
        elif line.startswith('|'):
            headers = cells(line)
            if i + 1 >= len(lines) or any(
                    not re.fullmatch(r':?-{3,}:?', cell) for cell in cells(lines[i + 1])):
                raise ValueError('design review table separator missing: ' + line)
            if len(cells(lines[i + 1])) != len(headers):
                raise ValueError('design review table separator width mismatch')
            i += 2
            rows = []
            while i < len(lines) and lines[i].strip().startswith('|'):
                row = cells(lines[i])
                if len(row) != len(headers):
                    raise ValueError('design review table width mismatch: ' + lines[i])
                rows.append('<tr>' + ''.join('<td>' + inline(x) + '</td>' for x in row) + '</tr>')
                i += 1
            out.append('<div class="tablewrap"><table><thead><tr>'
                       + ''.join('<th>' + inline(x) + '</th>' for x in headers)
                       + '</tr></thead><tbody>' + ''.join(rows) + '</tbody></table></div>')
        elif line.startswith('- '):
            items = []
            while i < len(lines) and lines[i].strip().startswith('- '):
                items.append('<li>' + inline(lines[i].strip()[2:]) + '</li>')
                i += 1
            out.append('<ul>' + ''.join(items) + '</ul>')
        else:
            if re.match(r'[#>`~]|\d+\.\s|[-*_]{3,}$|<', line) or lines[i] != lines[i].lstrip():
                raise ValueError('unsupported design review block: ' + line)
            paragraph = [line]
            i += 1
            while i < len(lines) and lines[i].strip():
                # 当前审阅区的段落按空行分隔；拒绝未支持的混合块。
                next_line = lines[i].strip()
                if next_line.startswith(('#', '|', '- ', '>', '```', '<')):
                    raise ValueError('design review block needs a blank line: ' + next_line)
                paragraph.append(next_line)
                i += 1
            out.append('<p>' + inline(' '.join(paragraph)) + '</p>')
    return '\n'.join(out)


def render_stage_inventory(cast, stage):
    """关卡清单直接读正式数据；明确桌子占位与实机可见是两回事。"""
    formal = load('StoryStageV2.json')
    legacy = {b['Id']: b for b in stage.get('Beats', []) if b.get('Cmd') == 'prop_spawn'}
    names = load_cn_names()
    by_id = {n['Id']: names.get(n.get('NameKey'), n.get('NameFallback', n['Id'])) for n in cast['Npcs']}
    labels = {
        'butcher_barrel': '屠户摊边杂物桶', 'butcher_block': '屠户操作桌',
        'pawnbroker_desk': '老周的当铺桌', 'pawnbroker_scale': '当铺杂物桶（不是秤）',
        'widow_carpet': '戏班前的地毯', 'widow_stage_a': '戏班左侧桌子（临时占位）',
        'widow_stage_b': '戏班右侧桌子（临时占位）',
    }
    rows = []
    for prop in formal['Layouts']['market_square']['Props']:
        key = prop['Id']
        previous = legacy.get(key)
        same = previous is not None and all(previous.get(k, 0) == prop.get(k, 0)
                                            for k in ('Prefab', 'Anchor', 'Fwd', 'Right', 'Up', 'Yaw'))
        rows.append('<tr>' + ''.join('<td>' + esc(v) + '</td>' for v in (
            labels.get(key, key), '1', key + ' / ' + prop.get('Prefab', '场景既有实体'),
            '以进入第二阶段时的玩家位置为基点：前 %.1f 米、右 %.1f 米；转 %.0f 度；贴地' %
            (prop.get('Fwd', 0), prop.get('Right', 0), prop.get('Yaw', 0)),
            '正式布局与旧台本一致；尚待逐件实机确认' if same else '正式布局与旧台本不同；须核对实际采用哪份位置',
        )) + '</tr>')
    actor_rows = []
    for key, label in [('first_meet', '第一次到城门'), ('second_meet', '第二次到门外市集')]:
        definition = formal['Stages'][key]
        actor_rows.append('<tr><td>' + label + '</td><td>'
                          + esc('、'.join(by_id.get(x, x) for x in definition['Actors']))
                          + '</td><td>' + str(len(definition['Props'])) + ' 件</td></tr>')
