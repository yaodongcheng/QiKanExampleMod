# -*- coding: utf-8 -*-
"""把序章的**配表数据**渲染成玩法演示页里的一节（2026-11-13 立）。

读三份正本：
    ModuleData/DesignData/StoryProbeCast.json
    ModuleData/DesignData/StoryProbeTuning.json
    ModuleData/DesignData/StoryStage.json
写进：
    plans/逆水寒511-玩法演示.html  的 CASTDATA 标记之间

🔴 页面这一节**是生成物**：改完表重跑本脚本，别手改（铁律 22）。
用法：python plans/逆水寒511/tools/gen_cast_html.py
"""
import io
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
DATA = os.path.join(ROOT, "ModuleData", "DesignData")
PAGE = os.path.join(ROOT, "plans", "逆水寒511-玩法演示.html")

BEGIN = "<!-- CASTDATA:BEGIN (generated by plans/nishuihan511/tools/gen_cast_html.py) -->"
END = "<!-- CASTDATA:END -->"

MONEY = {
    "Open": ("厚脸皮收", "var(--copper)"),
    "Covert": ("不当面收", "var(--amber)"),
    "Disdain": ("不屑", "var(--danger)"),
}

SKILL_CN = {"Trade": "交易", "Charm": "魅力", "Roguery": "巧计", "OneHanded": "单手", "Vigor": "体魄"}


def load(name):
    return json.load(io.open(os.path.join(DATA, name), encoding="utf-8"))


def load_cn_names():
    """NameKey -> 中文名（中文本地化层的 display name）。"""
    path = os.path.join(ROOT, "ModuleData", "Languages", "CNs", "std_LivingWorldNpcs_strings.xml")
    out = {}
    if not os.path.exists(path):
        return out
    text = io.open(path, encoding="utf-8").read()
    for m in re.finditer(r'<string id="([^"]+)" text="((?:[^"]|"")*)"', text):
        out[m.group(1)] = m.group(2).replace("&amp;", "&")
    return out


def esc(t):
    return (str(t).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def bar(value, color):
    v = max(0, min(100, int(value)))
    return ('<span class="cd-bar"><i style="width:%d%%;background:%s"></i></span>'
            '<span class="cd-num">%d</span>' % (v, color, v))


def build(cast, tune, stage, cn):
    npcs = cast.get("Npcs") or []
    factions = {f["Id"]: f for f in (cast.get("Factions") or [])}
    street = {s["NpcId"]: s for s in (cast.get("StreetLife") or [])}
    by_id = {n["Id"]: n for n in npcs}

    def nm(npc_id_or_def):
        """中文名：优先本地化层，其次 JSON 里的 fallback。"""
        n = npc_id_or_def if isinstance(npc_id_or_def, dict) else by_id.get(npc_id_or_def or "", {})
        return cn.get(n.get("NameKey", ""), n.get("NameFallback", n.get("Id", "")))

    # 台本里的站位
    placed = {}
    for b in (stage.get("Beats") or []):
        if b.get("Cmd") == "actor_place" and b.get("Actor"):
            placed[b["Actor"]] = b

    # 谁委托谁
    hired_by = {}
    for n in npcs:
        t = n.get("QuestTargetNpcId")
        if t:
            hired_by.setdefault(t, []).append(n["Id"])

    out = []
    w = out.append

    w('<section id="castdata">')
    w('  <h2>配表：每个人的数据</h2>')
    w('  <p class="sub">这一节由 <code>plans/逆水寒511/tools/gen_cast_html.py</code> 从 '
      '<code>StoryProbeCast.json</code> / <code>StoryProbeTuning.json</code> / <code>StoryStage.json</code> '
      '自动生成 —— <b>改表后重跑脚本，页面永远和游戏一致</b>。策划要改的就是这三份文件，不碰代码。</p>')

    w('  <style>')
    w('  .cd-grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:14px;margin-top:18px}')
    w('  .cd-card{background:var(--panel);border:1px solid var(--line);border-radius:12px;padding:15px 16px;box-shadow:var(--shadow)}')
    w('  .cd-head{display:flex;align-items:baseline;gap:8px;flex-wrap:wrap;margin-bottom:10px}')
    w('  .cd-head b{font-family:var(--serif);font-size:19px}')
    w('  .cd-id{font-size:12px;color:var(--muted);font-family:ui-monospace,Menlo,monospace}')
    w('  .cd-fac{font-size:11px;padding:2px 8px;border-radius:999px;background:var(--chip);color:var(--muted)}')
    w('  .cd-row{display:grid;grid-template-columns:52px 1fr;gap:10px;padding:5px 0;border-top:1px dashed var(--line);font-size:13.5px}')
    w('  .cd-row:first-of-type{border-top:0}')
    w('  .cd-k{color:var(--muted);font-size:12px;letter-spacing:.06em}')
    w('  .cd-bar{display:inline-block;width:74px;height:7px;border-radius:4px;background:var(--chip);vertical-align:middle;margin-right:6px;overflow:hidden}')
    w('  .cd-bar i{display:block;height:100%;border-radius:4px}')
    w('  .cd-num{font-size:12px;color:var(--muted);font-variant-numeric:tabular-nums;margin-right:10px}')
    w('  .cd-code{font-family:ui-monospace,Menlo,monospace;font-size:12px;background:var(--chip);padding:1px 6px;border-radius:5px;margin:0 4px 3px 0;display:inline-block;max-width:100%;overflow-wrap:anywhere}')
    w('  .cd-row>span{min-width:0;overflow-wrap:anywhere}')
    w('  .cd-attrs{display:grid;gap:2px}')
    w('  .cd-attrs i{font-style:normal;white-space:nowrap;font-size:12px;color:var(--muted)}')
    w('  .cd-tag{font-size:12px;padding:2px 8px;border-radius:6px;color:#fff;font-weight:600}')
    w('  .cd-tl{position:relative;margin:8px 0 4px;padding:10px 0;border-left:2px solid var(--line)}')
    w('  .cd-beat{position:relative;padding:3px 0 3px 16px;font-size:13px}')
    w('  .cd-beat .t{display:inline-block;min-width:44px;color:var(--copper);font-variant-numeric:tabular-nums;font-weight:600}')
    w('  .cd-beat .c{font-family:ui-monospace,Menlo,monospace;font-size:12px;background:var(--chip);padding:1px 6px;border-radius:5px;margin-right:6px}')
    w('  .cd-beat::before{content:"";position:absolute;left:-5px;top:11px;width:8px;height:8px;border-radius:50%;background:var(--copper)}')
    w('  </style>')

    # ── 九张卡 ──
    w('  <div class="cd-grid">')
    for n in npcs:
        nid = n["Id"]
        fac = factions.get(n.get("Faction"), {})
        money = n.get("Money") or "Disdain"
        mlabel, mcolor = MONEY.get(money, MONEY["Disdain"])
        age = n.get("Age", -1)
        sex = "女" if n.get("Female") else "男"
        civ = "平民装" if n.get("Civilian", True) else "战斗装"
        roles = []
        if n.get("IsBlocker"):
            roles.append("守门人")
        if n.get("QuestTargetNpcId"):
            roles.append("委托人")
        if nid in hired_by:
            roles.append("被" + "、".join(nm(x) for x in hired_by[nid] if x in by_id) + "盯上")

        w('    <article class="cd-card">')
        w('      <div class="cd-head"><b>%s</b><span class="cd-id">%s</span>'
          '<span class="cd-fac">%s</span>%s</div>'
          % (esc(nm(n)), nid,
             esc(fac.get("NameFallback", n.get("Faction", ""))),
             "".join('<span class="cd-fac">%s</span>' % esc(r) for r in roles)))

        w('      <div class="cd-row"><span class="cd-k">外观</span><span><code class="cd-code">%s</code>%s 岁 · %s · %s</span></div>'
          % (esc(n.get("TemplateId", "")), ("%d" % age) if age != -1 else "?", sex, civ))

        w('      <div class="cd-row"><span class="cd-k">三维</span><span class="cd-attrs">'
          '<i>武%s</i><i>技%s</i><i>魅%s</i></span></div>'
          % (bar(n.get("Force", 0), "var(--danger)"),
             bar(n.get("Guile", 0), "var(--amber)"),
             bar(n.get("Charm", 0), "var(--charm)")))

        if money == "Disdain":
            money_txt = '<span class="cd-tag" style="background:%s">%s</span> 给钱是侮辱' % (mcolor, mlabel)
        elif money == "Open":
            money_txt = '<span class="cd-tag" style="background:%s">%s</span> 当面 <b>%d</b> 第纳尔' % (mcolor, mlabel, n.get("MoneyPrice", 0))
        else:
            money_txt = '<span class="cd-tag" style="background:%s">%s</span> 走「买卖」才收 <b>%d</b> 第纳尔' % (mcolor, mlabel, n.get("MoneyCovertPrice", 0))
        w('      <div class="cd-row"><span class="cd-k">对钱</span><span>%s</span></div>' % money_txt)

        tgt = n.get("QuestTargetNpcId")
        if tgt:
            rewards = "、".join(n.get("RewardItems") or []) or "—"
            w('      <div class="cd-row"><span class="cd-k">委托</span><span>去 <b>%s</b>（%s）· 交差给 %s</span></div>'
              % (esc(nm(tgt)), esc(tgt), esc(rewards)))
        elif nid in hired_by:
            w('      <div class="cd-row"><span class="cd-k">委托</span><span>自己是别人的目标（%s 要办他）</span></div>'
              % esc("、".join(nm(x) for x in hired_by[nid])))
        else:
            w('      <div class="cd-row"><span class="cd-k">委托</span><span>不派活</span></div>')

        item = n.get("AttrItemId")
        if item:
            w('      <div class="cd-row"><span class="cd-k">能偷</span><span><code class="cd-code">%s</code> → %s +1</span></div>'
              % (esc(item), esc(SKILL_CN.get(n.get("AttrSkill"), n.get("AttrSkill", "")))))
        else:
            w('      <div class="cd-row"><span class="cd-k">能偷</span><span>身上没有属性道具</span></div>')

        acts = (street.get(nid) or {}).get("Actions") or []
        w('      <div class="cd-row"><span class="cd-k">常驻</span><span>%s</span></div>'
          % ("".join('<code class="cd-code">%s</code>' % esc(a) for a in acts) or "—"))

        pl = placed.get(nid)
        if pl:
            w('      <div class="cd-row"><span class="cd-k">站位</span><span>锚点 <b>%s</b> · 前 %.1f 米 · 右 %.1f 米 · %s</span></div>'
              % (esc(pl.get("Anchor", "player")), pl.get("Fwd", 0), pl.get("Right", 0),
                 "面朝玩家" if pl.get("Facing", -1) < -0.5 else "%.0f°" % pl.get("Facing", 0)))
        else:
            w('      <div class="cd-row"><span class="cd-k">站位</span><span>前 %.1f 米 · 右 %.1f 米（相对玩家）</span></div>'
              % (n.get("OffsetForward", 0), n.get("OffsetRight", 0)))

        w('    </article>')
    w('  </div>')

    # ── 横向对比 ──
    w('  <h3>一眼对比</h3>')
    w('  <div class="tablewrap"><table>')
    w('    <thead><tr><th>谁</th><th>武 / 技 / 魅</th><th>对钱</th><th>能给你什么</th><th>他的用处</th></tr></thead>')
    w('    <tbody>')
    for n in npcs:
        money = n.get("Money") or "Disdain"
        mlabel, mcolor = MONEY.get(money, MONEY["Disdain"])
        if money == "Open":
            mtxt = "%s（%d）" % (mlabel, n.get("MoneyPrice", 0))
        elif money == "Covert":
            mtxt = "%s（%d）" % (mlabel, n.get("MoneyCovertPrice", 0))
        else:
            mtxt = mlabel
        give = "、".join(n.get("RewardItems") or []) or "—"
        use = []
        if n.get("IsBlocker"):
            use.append("过门")
        if n.get("QuestTargetNpcId"):
            use.append("派活")
        if n.get("AttrItemId"):
            use.append("可偷")
        if n["Id"] in hired_by:
            use.append("被打")
        w('      <tr><td>%s</td><td class="mono">%d / %d / %d</td>'
          '<td><span class="cd-tag" style="background:%s">%s</span></td><td>%s</td><td>%s</td></tr>'
          % (esc(nm(n)), n.get("Force", 0), n.get("Guile", 0), n.get("Charm", 0),
             mcolor, esc(mtxt), esc(give), esc("、".join(use) or "—")))
    w('    </tbody>')
    w('  </table></div>')

    # ── 出场演出 ──
    beats = stage.get("Beats") or []
    w('  <h3>出场演出：%d 条指令</h3>' % len(beats))
    w('  <p class="sub">正本 = <code>StoryStage.json</code>。冻结玩家 → 生成布景 → 摆人 → 切镜头 → 交还。</p>')
    w('  <div class="cd-tl">')
    for b in beats:
        detail = b.get("Note") or ""
        bits = []
        for k in ("Actor", "Id", "Prefab", "Case", "Anchor", "Action"):
            if b.get(k):
                bits.append("%s=%s" % (k, b[k]))
        if bits:
            detail = (detail + "  " if detail else "") + " · ".join(bits)
        w('    <div class="cd-beat"><span class="t">%.1fs</span><span class="c">%s</span>%s</div>'
          % (b.get("At", 0), esc(b.get("Cmd", "")), esc(detail)))
    w('  </div>')

    anchors = stage.get("Anchors") or {}
    if anchors:
        w('  <p class="simnote">语义位（台本里写名字、运行时去场景找点）：'
          + "；".join('<code>%s</code> → 场景标签 %s' % (esc(k), esc("/".join(v))) for k, v in anchors.items())
          + '；另有内置的 <code>player</code> / <code>gate</code> / <code>gate_inner</code>。</p>')

    # ── 节奏参数 ──
    w('  <h3>节奏与几何（StoryProbeTuning.json）</h3>')
    w('  <p class="sub">觉得太慢、太快、门太好过——改这张表，<code>custom.story_probe reload</code> 生效。</p>')
    w('  <div class="tablewrap"><table>')
    w('    <thead><tr><th>段</th><th>键</th><th>值</th></tr></thead><tbody>')
    for sec, obj in tune.items():
        if not isinstance(obj, dict):
            continue
        for k, v in obj.items():
            if k.startswith("_"):
                continue
            w('      <tr><td>%s</td><td class="mono">%s</td><td class="mono">%s</td></tr>'
              % (esc(sec), esc(k), esc(v)))
    w('    </tbody></table></div>')

    w('</section>')
    return "\n".join(out)


def main():
    cast = load("StoryProbeCast.json")
    tune = load("StoryProbeTuning.json")
    stage = load("StoryStage.json")

    cn = load_cn_names()
    block = BEGIN + "\n" + build(cast, tune, stage, cn) + "\n" + END

    page = io.open(PAGE, encoding="utf-8").read()
    if BEGIN in page and END in page:
        head = page[:page.index(BEGIN)]
        tail = page[page.index(END) + len(END):]
        page = head + block + tail
        mode = "replaced"
    else:
        marker = "  <section>\n    <h2>怎么验（照着打，看日志）</h2>"
        if marker not in page:
            raise SystemExit("anchoring failed: cannot find the '怎么验' section")
        page = page.replace(marker, block + "\n" + marker, 1)
        mode = "inserted"

    io.open(PAGE, "w", encoding="utf-8", newline="").write(page)
    print("cast html %s: npcs=%d beats=%d bytes=%d" % (
        mode, len(cast.get("Npcs") or []), len(stage.get("Beats") or []), len(page)))


if __name__ == "__main__":
    main()
