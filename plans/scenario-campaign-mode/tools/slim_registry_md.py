# -*- coding: utf-8 -*-
"""16 瘦身重构：删除 CSV 大表渲染（查询处 = 16-DSL翻译总表.csv），16 = 查询指引 + 机制定义"""
import re

MD = 'plans/scenario-campaign-mode/16-DSL注册表全表.md'
t = open(MD, encoding='utf-8').read()

# 1) 替换第一部分（# 第一部分 ... # 第二部分 之前）→ 查询指引 + 操作符
new_head = '''# 一、查询指引（词条翻译 → 查 16-DSL翻译总表.csv）

> 🔴 **翻译大表 = `16-DSL翻译总表.csv`**（本 plan 数据文件，424 行：域 42 / 属性 199 / 命令 174 / 谓词 9）。
> 列 = 太阁原词 · 频率 · 类别 · 我们侧名 · 类型 · 语义 · 参数 · 实现用法 · 状态——**查询词条翻译只看这一处**。
> 生成：`tools/build_registry_csv.py`（字典+规则）→ CSV；01 validator 注册表检查读同一 CSV。
> 本文件其余部分 = **机制定义**（CSV 装不下的机制性内容）。

## 二、操作符统计（DSL 语法层，01 管）

| 操作符 | 次数 | 说明 |
|---|---|---|
| `==` | 22657 | 相等（最常用：身份/归属/状态判断） |
| `!=` | 4233 | 不等 |
| `>=` | 2633 | 数值门槛（年份/日数/数值属性） |
| `<` / `>` / `<=` | 686 / 431 / 410 | 数值比较 |
| 存在性（无操作符） | 9525 | `exists(大名家::X)` 式：势力/人物/组织是否存在 |

'''
t, n = re.subn(r'# 第一部分：太阁5 ↔ 骑砍2 翻译总表.*?(?=# 第二部分：机制定义)', new_head, t, flags=re.DOTALL)
assert n == 1, '第一部分替换失败 n=%d' % n

# 2) 删除 "# 第二部分：机制定义" 标题及其定位说明（编号重排后不再需要两部分结构）
t, n = re.subn(r'# 第二部分：机制定义（总表之外的机制权威）\n> 🔴 2026-08-26 重构：.*?(?=## 二、🔴 代入槽机制)', '', t, flags=re.DOTALL)
assert n == 1, '第二部分标题删除失败 n=%d' % n

# 3) 编号重排：## 二、Ctx → ## 三；## 三、trigger → ## 四；## 四、覆盖结论 → ## 五
t = t.replace('## 二、🔴 代入槽机制（Ctx 上下文变量，太阁"人物Ａ/主人公/發生據點"的映射）',
              '## 三、🔴 代入槽机制（Ctx 上下文变量，太阁"人物Ａ/主人公/發生據點"的映射）')
t = t.replace('## 三、触发时机注册表（trigger / once / priority，2026-08-26 新增）',
              '## 四、触发时机注册表（trigger / once / priority，2026-08-26 新增）')
t = t.replace('## 四、覆盖结论', '## 五、覆盖结论')

open(MD, 'w', encoding='utf-8').write(t)
print('16 瘦身重构完成')
